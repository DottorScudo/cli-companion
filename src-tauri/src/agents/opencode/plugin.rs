//! Generazione dei file del plugin OpenCode (puro): `index.ts` dal modello
//! `plugin.ts` e una `SKILL.md` per preset.
//!
//! La prima riga di `index.ts` e' un'intestazione fissa con la versione: serve
//! a riconoscere una cartella NOSTRA prima di sovrascriverla o toglierla.

use super::plugin_skills::skill_path;
use super::{AGENT_ID, MCP_SERVER, PLUGIN};
use crate::agents::fnv32;
use crate::agents::presets::{Preset, PRESETS};
use std::path::Path;

/// File del plugin che OpenCode carica.
pub(super) const INDEX_FILE: &str = "index.ts";

/// Modello del plugin: i segnaposto `__NOME__` diventano valori JSON.
const TEMPLATE: &str = include_str!("plugin.ts");

const PLACEHOLDER_NOTIFY_COMMAND: &str = "__NOTIFY_COMMAND__";
const PLACEHOLDER_AGENT_ID: &str = "__AGENT_ID__";
const PLACEHOLDER_MCP_SERVER: &str = "__MCP_SERVER__";
const PLACEHOLDER_SKILL_IDS: &str = "__SKILL_IDS__";
const PLACEHOLDER_PLUGIN: &str = "__PLUGIN__";

/// Parti fisse dell'intestazione: `// cli-companion-notify <versione>: generated by ...`.
const MARKER_START: &str = "// cli-companion-notify ";
const MARKER_END: &str = ": generated by cli-companion, reinstalling overwrites this folder.";

/// Valore JSON di una stringa o di una lista: mai quoting a mano.
fn json<T: serde::Serialize + ?Sized>(value: &T) -> String {
    serde_json::to_string(value).unwrap_or_default()
}

/// Tutte le skill dei preset in un solo testo (serve alla versione del plugin).
fn skills_blob() -> String {
    PRESETS.iter().map(Preset::skill_text).collect::<Vec<_>>().join("\n")
}

/// `index.ts` senza intestazione, per l'exe `exe` (come lo vede l'agente).
fn index_body(exe: &str) -> String {
    let skill_ids: Vec<&str> = PRESETS.iter().map(|p| p.id).collect();
    TEMPLATE
        .replace("\r\n", "\n")
        .replace(PLACEHOLDER_NOTIFY_COMMAND, &json(&[exe]))
        .replace(PLACEHOLDER_AGENT_ID, &json(AGENT_ID))
        .replace(PLACEHOLDER_MCP_SERVER, &json(MCP_SERVER))
        .replace(PLACEHOLDER_SKILL_IDS, &json(&skill_ids))
        .replace(PLACEHOLDER_PLUGIN, &json(PLUGIN))
}

/// La versione dipende dalla release dell'app e dal contenuto generato (exe,
/// plugin, skill): se cambia l'exe (app spostata), una skill o la release, la
/// reinstallazione deve riscrivere la cartella.
fn version_of(body: &str, skills: &str) -> String {
    format!("{}-h{:08x}", env!("CARGO_PKG_VERSION"), fnv32(&format!("{body}\n{skills}")))
}

/// Versione che avrebbe il plugin generato ora per `exe`.
pub(super) fn plugin_version_for(exe: &str) -> String {
    version_of(&index_body(exe), &skills_blob())
}

/// File del plugin (path relativo alla sua cartella, contenuto).
/// `String` -> file: UTF-8 senza BOM.
pub(super) fn plugin_files(exe: &str) -> Vec<(String, String)> {
    let body = index_body(exe);
    let header = format!("{MARKER_START}{}{MARKER_END}", version_of(&body, &skills_blob()));
    let mut files = vec![(INDEX_FILE.to_string(), format!("{header}\n{body}"))];
    files.extend(PRESETS.iter().map(|p| (skill_path(p), p.skill_text())));
    files
}

/// La prima riga e' l'intestazione fissa: il file e' stato generato da noi.
pub(super) fn has_marker(index_content: &str) -> bool {
    let first = index_content.lines().next().unwrap_or_default();
    first.starts_with(MARKER_START) && first.ends_with(MARKER_END)
}

/// `true` se `folder` e' un nostro plugin installato (il suo `index.ts` porta l'intestazione).
pub(super) fn is_ours(folder: &Path) -> bool {
    std::fs::read_to_string(folder.join(INDEX_FILE)).is_ok_and(|content| has_marker(&content))
}

#[cfg(test)]
mod tests {
    use super::*;

    const EXE: &str = "C:/Program Files/cli-companion/cli-companion.exe";

    fn file<'a>(files: &'a [(String, String)], path: &str) -> &'a str {
        &files.iter().find(|(p, _)| p == path).unwrap_or_else(|| panic!("manca {path}")).1
    }

    #[test]
    fn index_is_the_template_with_json_values_and_no_placeholder_left() {
        let files = plugin_files(EXE);
        let index = file(&files, INDEX_FILE);
        assert!(
            index.contains(r#"const NOTIFY_COMMAND: string[] = ["C:/Program Files/cli-companion/cli-companion.exe"]"#)
        );
        assert!(index.contains(r#"const AGENT_ID = "opencode""#));
        assert!(index.contains(r#"const MCP_SERVER = "cli-companion""#));
        assert!(index.contains(r#"const SKILL_IDS: string[] = ["task-intake","skill-wizard","project-setup"]"#));
        assert!(index.contains(r#"id: "cli-companion-notify","#));
        assert!(!index.contains("__"), "segnaposto rimasto");
        assert!(!index.contains('\r'));
    }

    #[test]
    fn the_exe_is_json_encoded_never_hand_quoted() {
        let files = plugin_files(r#"C:\odd "name"\app.exe"#);
        assert!(file(&files, INDEX_FILE).contains(r#"= ["C:\\odd \"name\"\\app.exe"]"#));
    }

    #[test]
    fn first_line_is_the_marker_with_the_version() {
        let files = plugin_files(EXE);
        let index = file(&files, INDEX_FILE);
        let first = index.lines().next().unwrap();
        assert_eq!(
            first,
            format!(
                "// cli-companion-notify {}: generated by cli-companion, reinstalling overwrites this folder.",
                plugin_version_for(EXE)
            )
        );
        assert!(has_marker(index));
    }

    #[test]
    fn marker_is_not_fooled_by_foreign_files() {
        for foreign in [
            "",
            "export default {}",
            "// my own plugin\n",
            "// cli-companion-notify 1.0.0\n",
            "\n// cli-companion-notify 1: generated by cli-companion, reinstalling overwrites this folder.",
        ] {
            assert!(!has_marker(foreign), "{foreign:?}");
        }
        // Un file riscritto con fine riga CRLF resta riconosciuto.
        assert!(has_marker(&format!("{MARKER_START}1.0.0{MARKER_END}\r\nrest")));
    }

    #[test]
    fn one_skill_per_preset_with_the_exact_text() {
        let files = plugin_files(EXE);
        assert_eq!(files.len(), 1 + PRESETS.len());
        for preset in PRESETS {
            assert_eq!(file(&files, &format!("skills/{}/SKILL.md", preset.id)), preset.skill_text());
        }
    }

    #[test]
    fn version_follows_the_exe_and_the_release() {
        let version = plugin_version_for(EXE);
        assert!(version.starts_with(env!("CARGO_PKG_VERSION")) && version.contains("-h"), "{version}");
        assert_eq!(version, plugin_version_for(EXE));
        assert_ne!(version, plugin_version_for("C:/other/cli-companion.exe"));
    }

    #[test]
    fn is_ours_reads_the_index_of_a_folder() {
        let dir = std::env::temp_dir().join(format!("mc-oc-plugin-ours-{}", std::process::id()));
        let _ = std::fs::remove_dir_all(&dir);
        assert!(!is_ours(&dir));
        std::fs::create_dir_all(&dir).unwrap();
        assert!(!is_ours(&dir));
        std::fs::write(dir.join(INDEX_FILE), "export default {}").unwrap();
        assert!(!is_ours(&dir));
        std::fs::write(dir.join(INDEX_FILE), &plugin_files(EXE)[0].1).unwrap();
        assert!(is_ours(&dir));
        let _ = std::fs::remove_dir_all(&dir);
    }
}
